// Ships the avatar renders into the app:
//   node tool/blender/avatar_ship.js docs/renders/avatar
// copies every layer PNG to assets/images/avatar/<view>/<layer>/<id>.png, adds each folder to
// pubspec.yaml (Flutter does not recurse) and writes lib/features/avatar/avatar_layers.g.dart
// (the set of layer files that exist, so a part without a file for some layer is skipped).
const fs = require('fs');
const path = require('path');

const src = process.argv[2] || 'docs/renders/avatar';
const dst = 'assets/images/avatar';
const layers = new Set();
const dirs = [];

for (const view of ['full', 'bust']) {
  const vdir = path.join(src, view);
  if (!fs.existsSync(vdir)) continue;
  for (const layer of fs.readdirSync(vdir)) {
    const ldir = path.join(vdir, layer);
    if (!fs.statSync(ldir).isDirectory()) continue;
    const out = path.join(dst, view, layer);
    fs.mkdirSync(out, { recursive: true });
    for (const f of fs.readdirSync(ldir)) {
      if (!f.endsWith('.png')) continue;
      fs.copyFileSync(path.join(ldir, f), path.join(out, f));
      if (view === 'full') layers.add(layer + '/' + f.replace(/\.png$/, ''));
    }
    dirs.push(`    - ${dst}/${view}/${layer}/`);
  }
}

// pubspec: replace the avatar block (between the markers) or add it after the owl_s2 line.
let p = fs.readFileSync('pubspec.yaml', 'utf8');
const crlf = p.includes('\r\n');
if (crlf) p = p.replace(/\r\n/g, '\n');
const begin = '    # avatar layers (generated by tool/blender/avatar_ship.js)';
const end = '    # end avatar layers';
const block = [begin, ...dirs, end].join('\n');
if (p.includes(begin)) {
  p = p.replace(new RegExp(begin.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + end), block);
} else {
  p = p.replace('    - assets/images/ui_px/\n', '    - assets/images/ui_px/\n' + block + '\n');
}
if (crlf) p = p.replace(/\n/g, '\r\n');
fs.writeFileSync('pubspec.yaml', p);

const sorted = [...layers].sort();
const dart = `// GENERATED by tool/blender/avatar_ship.js from the avatar renders - do not edit.
// The layer pictures that exist (layer/id); AvatarSpec.layers() skips the rest.
const Set<String> kAvatarLayerFiles = {
${sorted.map((l) => `  '${l}',`).join('\n')}
};
`;
fs.mkdirSync('lib/features/avatar', { recursive: true });
fs.writeFileSync('lib/features/avatar/avatar_layers.g.dart', dart);
console.log('layers', sorted.length, 'dirs', dirs.length);
